"""Write ECOSYSTEM.md, the map of the library and the repositories it runs in.

  python3 scripts/architecture.py            rewrite ECOSYSTEM.md
  python3 scripts/architecture.py --check    exit 1 when it is out of date

The page is drawn from what decides the architecture, so it cannot drift
from it: ecosystem.json for the repositories and what each one takes, the
package's own source for its modules, their imports and their one-line
summaries (the first sentence of each docstring). scripts/check.sh runs
the --check form, so a change to either that leaves the page behind fails
the check named "check" until the page is regenerated with it. GitHub
renders the page's Mermaid charts itself, with nothing to install.
"""

import argparse
import ast
import re
import sys
from pathlib import Path

import ecosystem
import sync

PAGE = ecosystem.ROOT / "ECOSYSTEM.md"
REGENERATE = "python3 scripts/architecture.py"
FIRST_SENTENCE = re.compile(r"(.+?[.!?])(?:\s|$)")
ANGLED = re.compile(r"[\w./-]*<[^<>\s]+>[\w/-]*")
NUMBERS = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight", 9: "Nine"}


# --- words ---------------------------------------------------------------------------------

def summary_of(relative, package_dir=ecosystem.PACKAGE_DIR):
    """The first sentence of a module's docstring, on one line."""
    docstring = ast.get_docstring(ast.parse((package_dir / relative).read_text(encoding="utf-8"))) or ""
    paragraph = " ".join(docstring.split("\n\n")[0].split())
    found = FIRST_SENTENCE.match(paragraph)
    return found.group(1) if found else paragraph


def code_spans(text):
    """Text with each <placeholder> word in a code span, which GitHub
    would otherwise read as an HTML tag and drop."""
    return ANGLED.sub(lambda found: f"`{found.group(0)}`", text)


def cell(text):
    return text.replace("|", "\\|")


def node_id(module):
    return "m_" + re.sub(r"\W", "_", module)


def repository_id(repository):
    return "r_" + re.sub(r"\W", "_", ecosystem.short_name(repository))


# --- sections ------------------------------------------------------------------------------

def header(eco):
    count = NUMBERS.get(len(eco["consumers"]), str(len(eco["consumers"])))
    return [
        "# The symphony-protocol ecosystem",
        "",
        f"Generated by `{REGENERATE}` from ecosystem.json and the package's source; change those, never "
        "this page, and regenerate it: `bash scripts/check.sh` fails while it is out of date.",
        "",
        f"The claim protocol's rules live once, in the package `{eco['package']}` of {eco['library']}. "
        f"{count} other repositories run a copy of it in their own tree, so their workflows and hooks need "
        "nothing but Python 3.12. ecosystem.json says which repository takes which modules and where; "
        f"`scripts/vendor.py` makes each copy and records it in `VENDORED`, and each consumer's own check "
        "holds the copy to that record, so a copy is only ever changed by the sync, never by hand.",
    ]


def repositories(eco):
    lines = ["", "## The repositories", "",
             f"- **{eco['library']}** (public, this repository): {eco['about']}"]
    lines += [f"- **{c['repository']}** ({c['visibility']}): {c['about']}" for c in eco["consumers"]]
    return lines


def taken(eco, consumer):
    if consumer["modules"] == ecosystem.ALL:
        return "all of it"
    return ", ".join(f"`{name}`" for name in consumer["modules"])


def consumers_table(eco):
    always = " and ".join(f"`{name}`" for name in eco["always_copied"])
    lines = ["", "## Who takes what", "",
             f"Every copy also takes {always}: the package's version, and the check a consumer runs on its "
             "copy, `python3 <vendor_dir>/sdlc_protocol/vendoring.py verify <vendor_dir>`.",
             "",
             "| Repository | Copy in | Modules | Uses it for | The sync's pull request merges by |",
             "| --- | --- | --- | --- | --- |"]
    for c in eco["consumers"]:
        merges = "auto-merge, once its check is green" if c["auto_merge"] else f"its owner ({c['visibility']}: no auto-merge)"
        lines.append(f"| {ecosystem.short_name(c['repository'])} | `{c['vendor_dir']}/{eco['package']}` | "
                     f"{taken(eco, c)} | {cell(c['uses'])} | {merges} |")
    return lines + version_files(eco)


def with_version_file(eco):
    return [c for c in eco["consumers"] if "version_file" in c]


def version_files(eco):
    named = with_version_file(eco)
    if not named:
        return []
    lines = ["",
             "A consumer that ships its copy on to users of its own names a version file in ecosystem.json. "
             "Whenever the copy's files change, `scripts/vendor.py` raises that file's patch version in the "
             "same run, so the sync's commit is also the release that takes the new copy to those users: "
             "Claude Code, for one, keeps an installed plugin on its cached copy until the version in the "
             "plugin's manifest changes.",
             ""]
    return lines + [f"- {ecosystem.short_name(c['repository'])}: `{c['version_file']}`" for c in named]


def module_graph(eco, modules):
    lines = ["", "## The modules and who takes them", "",
             "A solid arrow is an import, from the module that imports to the module it needs; a dotted "
             "arrow is a repository taking the whole package or the modules it names. The rules are plain "
             "functions over what they are handed; only the modules under `adapters/` call GitHub or change "
             "a git repository, and `cli` is the shell around them.",
             "", "```mermaid", "flowchart LR", f"  subgraph library[\"{eco['package']}\"]"]
    lines += [f"    {node_id(ecosystem.module_name(m))}[\"{ecosystem.module_name(m)}\"]" for m in modules]
    lines.append("  end")
    lines += [f"  {repository_id(c['repository'])}([\"{ecosystem.short_name(c['repository'])}\"])"
              for c in eco["consumers"]]
    lines += [f"  {node_id(ecosystem.module_name(module))} --> {node_id(ecosystem.module_name(needed))}"
              for module in modules for needed in ecosystem.imports_of(module)]
    for c in eco["consumers"]:
        if c["modules"] == ecosystem.ALL:
            lines.append(f"  {repository_id(c['repository'])} -. all .-> library")
        else:
            lines += [f"  {repository_id(c['repository'])} -.-> {node_id(ecosystem.module_name(m))}"
                      for m in c["modules"]]
    return lines + ["```"]


def module_summaries(modules):
    lines = ["", "What each module is, in the first sentence of its docstring:", ""]
    return lines + [f"- `{ecosystem.module_name(m)}`: {code_spans(summary_of(m))}" for m in modules]


def travel_chart(eco):
    lines = [
        "```mermaid",
        "flowchart LR",
        "  pr[\"pull request on symphony-protocol\"] --> checks[\"check, and downstream for each consumer\"]",
        "  checks --> merge[\"merge to main\"]",
        "  merge --> release[\"a release, on the merge, or once the owner approves it in Developer mode\"]",
        f"  release --> pulls[\"sync: the pull request {sync.BRANCH} in each consumer\"]",
        "  pulls --> theirs[\"the consumer's own check\"]",
        "  theirs --> lands[\"auto-merge, or the owner where there is none\"]",
    ]
    if with_version_file(eco):
        lines.append("  lands --> users[\"its users' installs, where it names a version file\"]")
    return lines + ["```"]


def release_steps(eco):
    """The steps of a change's journey that a version file adds, or none."""
    named = with_version_file(eco)
    if not named:
        return [], []
    files = ", ".join(f"{ecosystem.short_name(c['repository'])}'s `{c['version_file']}`" for c in named)
    raising = (f" Where a consumer names a version file ({files}), the same commit raises its patch version "
               "whenever the copy's files change.")
    reaching = ("6. Where the consumer names a version file, that merge is also its release: the installs "
                "that run its copy see the new version and take the new copy at their next update.")
    return [raising], [reaching]


def travel(eco):
    names = ", ".join(ecosystem.short_name(c["repository"]) for c in eco["consumers"])
    raising, reaching = release_steps(eco)
    return [
        "", "## How a change travels", "",
        *travel_chart(eco),
        "",
        "1. A pull request here runs the check named `check`, the library's own suite, and one "
        "`downstream (<consumer>)` job per consumer: the change vendored into a checkout of that "
        "consumer and the consumer's own check run on it, so a change that would break one is red "
        "before it merges.",
        "2. The owner merges it to main. Where it raises the version, its merge is a release: "
        "`.github/workflows/release.yml` tags it and publishes it on the merge, or, in Developer mode (the "
        "repository variable `SYMPHONY_DEVELOPER_MODE` set to `on`), once the owner approves the run in the "
        "environment `release`, and not before.",
        "3. The sync workflow (`.github/workflows/sync.yml`) follows each Release run that succeeds, and runs "
        "weekly and by hand; every run carries the newest published release, never main's head, into each "
        f"consumer ({names}) with that release's own `scripts/vendor.py`, and opens the pull request "
        f"`{sync.BRANCH}` there, or updates the one already open, with the GitHub App's token, so the "
        "consumer's own CI runs on it; where the consumer's main already holds the copy, it closes a sync pull "
        "request still open there." + "".join(raising),
        "4. The consumer's own check runs on that pull request; part of it is `vendoring.py verify`, "
        "which holds the copy to its record.",
        "5. Where ecosystem.json gives a consumer auto_merge, its pull request lands by auto-merge once "
        "that check is green; the others wait for their owner.",
        *reaching,
        "",
        "A consumer never edits its copy: the change is made here and comes back with the next release, by "
        "the sync. To vendor by hand, `python3 scripts/vendor.py <consumer checkout>` from a clone of this "
        "repository.",
        "",
        "A change a consumer must answer, such as a rendered string its test pins or a function it calls "
        "differently, turns that consumer's `downstream (<consumer>)` job red, and the sync cannot carry "
        f"it: it rebuilds `{sync.BRANCH}` from the consumer's main on every run, so a fix pushed there is "
        "lost. The consumer goes first: this pull request raises the version from the start, a pull request "
        "of the consumer's own vendors its branch and answers the change, and merges, ahead of the release, "
        "which is the one way a change reaches a consumer before its release; the downstream job "
        "here then turns green, this pull request merges, and once its release is made the sync "
        "finds that consumer up to date. README.md, \"How a change reaches the other repositories\", has "
        "the steps.",
    ]


def page(eco):
    modules = ecosystem.module_files()
    lines = (header(eco) + repositories(eco) + consumers_table(eco) + module_graph(eco, modules)
             + module_summaries(modules) + travel(eco))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(prog=f"{REGENERATE}", description="Write ECOSYSTEM.md, or check it.")
    parser.add_argument("--check", action="store_true", help="exit 1 when ECOSYSTEM.md is out of date")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    text = page(ecosystem.load())
    current = PAGE.read_text(encoding="ascii") if PAGE.is_file() else None
    if args.check:
        if current != text:
            print(f"ECOSYSTEM.md is out of date with ecosystem.json and sdlc_protocol/; run {REGENERATE} "
                  "and commit the result", file=sys.stderr)
            return 1
        print("ECOSYSTEM.md is up to date")
        return 0
    if current != text:
        PAGE.write_text(text, encoding="ascii", newline="\n")
    print(f"ECOSYSTEM.md: {'unchanged' if current == text else 'rewritten'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
